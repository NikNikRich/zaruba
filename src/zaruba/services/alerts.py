"""Плашка срочного оповещения (`docs/09` §9.9).

Логика ровно одна: какое оповещение показывать. Выбор строки — по данным, а не
по вёрстке, поэтому шаблон не перебирает список и не решает, «достаточно ли
срочно»: `urgent` и `status` пришли из таблицы организаторов.
"""

from __future__ import annotations

from collections.abc import Sequence

from ..models import Alert


def active_alert(alerts: Sequence[Alert]) -> Alert | None:
    """Первое опубликованное срочное оповещение; `None` — плашки нет.

    Берём именно первое: таблица читается сверху вниз, и владелец ставит новую
    строку над старой. Так порядок плашки — это порядок в Google Таблице, а не
    ещё один столбец «приоритет», который забудут заполнить.
    """

    return next((item for item in alerts if item.in_feed), None)
